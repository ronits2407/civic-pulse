import React, { useCallback, useMemo, useState } from 'react'
import { StyleSheet, View } from 'react-native'
import { Image } from 'expo-image'
import { useLocalSearchParams } from 'expo-router'
import * as Sharing from 'expo-sharing'
import * as Linking from 'expo-linking'
import { File, Paths } from 'expo-file-system'

import { Button } from '@/components/ui/Button'
import { Card } from '@/components/ui/Card'
import { ErrorState, Notice } from '@/components/ui/Feedback'
import { Screen } from '@/components/ui/Screen'
import { Text } from '@/theme/Typography'
import { Icon } from '@/theme/icons'
import { env } from '@/lib/env'
import { accent, ink, line, radius, space, surface } from '@/theme/tokens'

/**
 * Impact receipt.
 *
 * The image is produced by the existing Next.js route at `/receipt/[issue_id]` — a
 * server-rendered OG card. This screen does not recreate that logic; it displays the
 * route's output and lets the citizen share the file on Android.
 *
 * Because the route is server-rendered at 1200×630, the app downloads it once to the
 * cache directory so the Android share sheet receives a real file rather than a URL.
 */
export default function ReceiptScreen() {
  const params = useLocalSearchParams<{ issueId?: string }>()
  const issueId = typeof params.issueId === 'string' ? params.issueId : null

  const [sharing, setSharing] = useState(false)
  const [shareError, setShareError] = useState<string | null>(null)
  const [imageFailed, setImageFailed] = useState(false)

  const receiptUrl = useMemo(
    () => (issueId && env.apiUrl ? `${env.apiUrl}/receipt/${issueId}` : null),
    [issueId]
  )

  const share = useCallback(async () => {
    if (!receiptUrl || sharing) return
    setSharing(true)
    setShareError(null)
    try {
      const available = await Sharing.isAvailableAsync()
      if (!available) {
        // No share sheet (rare on Android). Opening the browser is still useful.
        await Linking.openURL(receiptUrl)
        return
      }
      const file = await File.downloadFileAsync(receiptUrl, Paths.cache)
      await Sharing.shareAsync(file.uri, {
        mimeType: 'image/png',
        dialogTitle: 'Share your impact receipt',
      })
    } catch (err: any) {
      setShareError(err?.message ?? 'Could not prepare the receipt for sharing.')
    } finally {
      setSharing(false)
    }
  }, [receiptUrl, sharing])

  if (!issueId || !receiptUrl) {
    return (
      <Screen padded>
        <ErrorState
          title="No receipt available"
          message="This link does not include a report to build a receipt from."
        />
      </Screen>
    )
  }

  return (
    <Screen scroll padded contentContainerStyle={styles.content}>
      <Text variant="title">Impact receipt</Text>
      <Text variant="caption" tone="faint">
        Generated by CivicPulse from the details of this report and its resolution.
      </Text>

      <Card padded={false} style={styles.imageCard}>
        {imageFailed ? (
          <View style={styles.imageFallback}>
            <Icon name="image-off-outline" size={22} color={ink.faint} />
            <Text variant="caption" tone="muted" center style={styles.fallbackText}>
              The receipt image could not be loaded. Check that the backend is reachable
              and try again.
            </Text>
          </View>
        ) : (
          <Image
            source={{ uri: receiptUrl }}
            style={styles.image}
            contentFit="contain"
            transition={220}
            onError={() => setImageFailed(true)}
          />
        )}
      </Card>

      {shareError ? <Notice tone="red" body={shareError} title="Sharing failed" /> : null}

      <View style={styles.actions}>
        <Button
          label={sharing ? 'Preparing…' : 'Share receipt'}
          onPress={share}
          loading={sharing}
          disabled={imageFailed}
          size="lg"
          fullWidth
          icon={<Icon name="share-variant-outline" size={17} color="#ffffff" />}
        />
        <Button
          label="Open in browser"
          onPress={() => Linking.openURL(receiptUrl)}
          variant="secondary"
          fullWidth
          icon={<Icon name="open-in-new" size={16} color={ink.base} />}
        />
      </View>

      <Notice
        tone="blue"
        body="The estimate of how many people benefited is derived from the issue category and severity. It is an illustration, not a survey."
        icon={<Icon name="information-outline" size={15} color={accent.blue} />}
      />
    </Screen>
  )
}

const styles = StyleSheet.create({
  content: { gap: space.lg, paddingBottom: space.huge },
  imageCard: { overflow: 'hidden', backgroundColor: surface.sunken },
  image: { width: '100%', aspectRatio: 1200 / 630 },
  imageFallback: { alignItems: 'center', justifyContent: 'center', gap: space.sm, paddingVertical: space.huge, paddingHorizontal: space.lg },
  fallbackText: { maxWidth: 280 },
  actions: { gap: space.md },
})
